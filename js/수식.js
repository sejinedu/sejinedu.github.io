// ============================================================
//  수식 — 자막 속 수식을 진짜 수식처럼 그린다 (KaTeX)
// ============================================================
//
//  사용자가 정한 것 (2026-09-02):
//    「라텍스가 이쁜데 나중에 적분이나 시그마 이런것도 해야 되」
//
//  ★★★ 왜 자막 파일은 안 건드리는가
//    자막 파일(.js/.srt)에는 「v₀ + ½at²」 처럼 보통 글자로 담아 둔다.
//    라텍스를 파일에 박으면 .srt 가 못 읽는 글이 되고,
//    나중에 안경(로라) 학습 재료로도 못 쓴다.
//    ⇒ 파일은 글자 그대로 두고, 화면에 그릴 때만 수식으로 바꾼다.
//
//  ★ KaTeX 는 자산/수식/ 에 넣어 뒀다. 인터넷 없이도 돈다.
//  ★ KaTeX 를 못 불러와도 자막은 글자 그대로 나온다. 화면이 죽지 않는다.

const 수식 = (() => {

  let 준비됨 = false;
  let 부르는중 = null;

  function 파일하나(만들기, 넣을것) {
    return new Promise(풀기 => {
      const ㅇ = 만들기();
      ㅇ.onload = () => 풀기(true);
      ㅇ.onerror = () => 풀기(false);
      넣을것(ㅇ);
    });
  }

  // KaTeX 를 딱 한 번만 불러온다.
  function 부르기() {
    if (준비됨) return Promise.resolve(true);
    if (부르는중) return 부르는중;
    부르는중 = (async () => {
      const 판 = window.판 || "0";
      await 파일하나(() => {
        const ㄹ = document.createElement("link");
        ㄹ.rel = "stylesheet";
        ㄹ.href = "자산/수식/katex.min.css?v=" + 판;
        return ㄹ;
      }, ㅇ => document.head.appendChild(ㅇ));
      const 됐나 = await 파일하나(() => {
        const ㅅ = document.createElement("script");
        ㅅ.src = "자산/수식/katex.min.js?v=" + 판;
        return ㅅ;
      }, ㅇ => document.head.appendChild(ㅇ));
      준비됨 = 됐나 && typeof window.katex !== "undefined";
      return 준비됨;
    })();
    return 부르는중;
  }

  // ---------- 우리 글자 → 라텍스 ----------
  //
  //  자막에 담긴 것은 이미 다듬어진 글자다 — v₀ + ½at², 2π/T, sin²θ, m/s².
  //  그걸 라텍스로 옮긴다.

  const 아래숫자 = "₀₁₂₃₄₅₆₇₈₉";

  const 낱개 = [
    ["½", "\\tfrac12"], ["⅓", "\\tfrac13"], ["¼", "\\tfrac14"], ["¾", "\\tfrac34"],
    ["²", "^2"], ["³", "^3"], ["⁴", "^4"], ["⁺", "^+"], ["⁻", "^-"],
    ["₀", "_0"], ["₁", "_1"], ["₂", "_2"], ["₃", "_3"], ["₄", "_4"],
    ["₅", "_5"], ["₆", "_6"], ["₇", "_7"], ["₈", "_8"], ["₉", "_9"],
    ["×", "\\times "], ["÷", "\\div "], ["−", "-"], ["·", "\\cdot "],
    ["∫", "\\int "], ["∑", "\\sum "], ["Σ", "\\sum "],
    ["Δ", "\\Delta "], ["θ", "\\theta "], ["π", "\\pi "], ["ω", "\\omega "],
    ["λ", "\\lambda "], ["μ", "\\mu "], ["α", "\\alpha "], ["β", "\\beta "],
    ["γ", "\\gamma "], ["ρ", "\\rho "], ["℃", "^{\\circ}\\mathrm{C}"], ["°", "^{\\circ}"],
    ["≈", "\\approx "], ["≠", "\\neq "], ["≤", "\\leq "], ["≥", "\\geq "], ["∞", "\\infty "]
  ];

  // 화학식인가? — 큰 글자로 시작하고, 셈 기호가 없고, 아래첨자가 있으면 화학식으로 본다.
  function 화학식인가(조각) {
    const ㄱ = 조각.trim();
    if (!/^[A-Z]/.test(ㄱ)) return false;
    if (/[+\-−×÷=^/·]/.test(ㄱ)) return false;
    return /^[A-Za-z()₀-₉]+$/.test(ㄱ) && /[₀-₉]/.test(ㄱ);
  }

  function 아래첨자풀기(글) {
    return 글.replace(/[₀-₉]+/g, ㅁ =>
      "_{" + ㅁ.split("").map(ㄱ => 아래숫자.indexOf(ㄱ)).join("") + "}");
  }

  function 라텍스로(조각) {
    // ★ 화학식은 기울이지 않는다 — CO₂, H₂O, Ca(OH)₂ 는 곧게 세우는 게 규칙이다.
    if (화학식인가(조각)) {
      return 아래첨자풀기(조각.trim().replace(/([A-Za-z()]+)/g, "\\mathrm{$1}"));
    }

    let ㄱ = 조각;

    // ★ 한 덩어리 안에 화학식이 섞여 있을 때도 곧게 세운다 (2026-09-02 에 밟음)
    //   「CO₂, H₂O, Ca(OH)₂ 나옴」 처럼 쉼표로 묶이면 위 화학식인가() 가 못 잡는다.
    //   ⇒ 큰 글자로 시작하고 아래첨자가 붙은 토막만 골라서 곧게 세운다.
    //   ★★★ 「큰 글자 하나 + 아래첨자」 는 화학식이 아니다 — V₀, T₁, Q₂ 는 변수다.
    //     그래서 ① 글자가 둘 이상이거나 ② 아래첨자 뒤에 또 글자가 오는 것만 잡는다.
    //     (CO₂ 는 ①, H₂O 는 ②, Ca(OH)₂ 는 ① — V₀ 는 둘 다 아니라서 안 잡힌다)
    ㄱ = ㄱ.replace(/[A-Z](?:[A-Za-z()]+[₀-₉]+[A-Za-z()₀-₉]*|[₀-₉]+[A-Za-z()][A-Za-z()₀-₉]*)/g,
      ㅁ => 아래첨자풀기(ㅁ.replace(/([A-Za-z()]+)/g, "\\mathrm{$1}")));

    // sin cos tan 은 곧게 세운다
    // ★ 앞에 글자가 붙어 있어도 세운다 — mgcosθ 는 mg 곱하기 cosθ 다 (2026-09-02 에 밟음)
    //   \b 를 쓰면 mgcosθ 안의 cos 를 못 잡아서 통째로 기울어졌다.
    //   뒤에만 글자가 안 오게 막는다. log/ln/exp 는 남의 낱말 속에 잘 끼므로 앞도 막는다.
    ㄱ = ㄱ.replace(/(sin|cos|tan)(?![a-z])/g, "\\$1 ");
    ㄱ = ㄱ.replace(/\b(log|ln|exp)\b/g, "\\$1 ");

    // ★ 단위는 분수로 쌓지 않는다 — m/s, m/s², km/h 는 한 줄로 붙여 쓴다.
    //   (2026-09-02 에 두 번 밟음 — 「6m/s²」 가 6m 분의 s² 로 위아래로 쌓였다)
    //   ★★★ 여기서 「/」 를 그대로 두면 안 된다.
    //     바로 아래 분수 규칙이 \mathrm{m/s} 안의 「/」 를 또 집어서 분수로 만든다.
    //     그래서 잠깐 딴 글자(숨김빗금)로 바꿔 두고, 분수를 다 쌓은 뒤에 되돌린다.
    const 숨김빗금 = "";
    ㄱ = ㄱ.replace(/(\d*)\s*(k?m)\/(s|h)([²³])?/g,
      (통째, 수, 길이, 시간, 제곱) =>
        (수 || "") + "\\mathrm{" + 길이 + 숨김빗금 + 시간 + "}" +
        (제곱 === "²" ? "^2" : (제곱 === "³" ? "^3" : "")));

    // 나눗셈은 진짜 분수로 쌓는다 — 2π/T → 위아래로
    // ★ 쉼표·마침표·= 는 분수에 끌어들이지 않는다 (2026-09-02 에 밟음)
    //   「v²/R, ½at²」 에서 쉼표가 분모로 딸려 들어가 R, 이 되어 버렸다.
    ㄱ = ㄱ.replace(/([^\s/{},.=+-]+)\/([^\s/{},.=+-]+)/g, "\\frac{$1}{$2}");
    ㄱ = ㄱ.split(숨김빗금).join("/");

    // √ 는 뒤엣것을 씌운다
    ㄱ = ㄱ.replace(/√\s*([A-Za-z0-9]+)/g, "\\sqrt{$1}");
    ㄱ = ㄱ.split("√").join("\\sqrt ");

    낱개.forEach(([ㅁ, ㄴ]) => { ㄱ = ㄱ.split(ㅁ).join(ㄴ); });
    return ㄱ;
  }

  // ---------- 수식 자리 찾기 ----------
  //
  //  ★★★ 한글 사이에 낀 수식만 골라야 한다.
  //    아무 글자나 수식으로 그리면 「LED」, 「BTB」, 「A, B, C, D」 까지 망가진다.
  //    그래서 「수식에만 쓰는 글자」 가 하나라도 든 덩어리만 고른다.

  // ★★★ 빗금도 수식 표시다 (2026-09-03 · 사용자가 화면 보고 잡아냄)
  //   「3/5이 되겠죠」 가 그냥 글자로 나갔다. 3/5 은 분수라 라텍스가 그려야 한다.
  //   빗금이 든 토막은 나눗셈이거나 단위(m/s)다. 둘 다 수식으로 그리는 게 맞다.
  // ★ 등호와 밑줄도 수식 표시다 (2026-09-03 · 시험 화면을 눈으로 보고 잡음)
  //   「PV = nRT」 「t_H」 가 그냥 글자로 나갔다. 등호가 있으면 수식이고,
  //   밑줄은 아래첨자 표시다.
  const 수식글자 = /[₀-₉⁰-⁹²³½⅓¼¾×÷−√∫∑ΣΔθπωλμαβγρ°℃≈≠≤≥∞\/=_]/;

  // ★★★ 표시가 없어도 수식인 짧은 토막 (2026-09-03)
  //   「2as」 「2gh」 처럼 숫자+작은글자, 그리고 물리에서 늘 쓰는 짧은 꼴들.
  //   ★ 아무 영어 낱말이나 기울이면 안 된다. 그래서 목록으로 못 박는다.
  // ★★★ 숫자 뒤에 아무 글자나 오면 안 된다 (2026-09-03 · 되짚어 보다 잡음)
  //   「2kg」 「10cm」 「20m」 은 **단위**다. 단위는 곧게 세워야 한다 — 기울이면 틀린 표기다.
  //   그래서 숫자 뒤에는 **아는 수식 꼴만** 온다고 못 박는다.
  const 짧은수식 = /^(?:\d{1,3}(?:as|gh|at|gt|kx|ma|mv)|mg|ma|at|gt|kx|as|mv|gh|rF|Ft|Fs)$/;

  //  이 토막이 수식인가 — 한 자리에서 판단한다
  function 수식인가(토막) {
    if (!토막) return false;
    const ㄱ = 토막.trim();
    if (!ㄱ) return false;
    if (ㄱ.length === 1) return /^[A-Za-z]$/.test(ㄱ);   // 홑글자 변수 (a · g · v)
    return 짧은수식.test(ㄱ) || 수식글자.test(ㄱ);
  }
  const 덩어리 = /[A-Za-z0-9₀-₉⁰-⁹²³½⅓¼¾×÷−+\-/√∫∑ΣΔθπωλμαβγρ°℃≈≠≤≥∞().,^_= ]{1,}/g;

  function 나누기(글) {
    const 조각들 = [];
    let 끝난데 = 0;
    let ㅁ;
    덩어리.lastIndex = 0;
    while ((ㅁ = 덩어리.exec(글)) !== null) {
      let 몸통 = ㅁ[0];
      const 앞군더더기 = 몸통.match(/^[\s,.]*/)[0];
      const 뒤군더더기 = 몸통.match(/[\s,.]*$/)[0];
      const 시작 = ㅁ.index + 앞군더더기.length;
      몸통 = 몸통.slice(앞군더더기.length, 몸통.length - 뒤군더더기.length);
      // ★★★ 홑글자 변수도 수식으로 그린다 (2026-09-03 · 사용자가 정함)
      //   「그리고 a자리에 g를 넣으시면 됩니다」 — 여기 a·g 도 기울임체라야 한다.
      //   「아니 a 를 a말고 있자나 그 라텍스」
      //   ★ 홑글자 하나만 있는 토막은 수식 표시가 없어도 변수로 본다.
      //     한글 사이에 홀로 선 영문 글자는 물리·수학 변수뿐이다.
      const 홑변수 = 수식인가(몸통) && !수식글자.test(몸통);
      if (!몸통 || (!홑변수 && !수식글자.test(몸통))) continue;
      if (시작 > 끝난데) 조각들.push({ 글: true, 값: 글.slice(끝난데, 시작) });
      // ★★★ 문장이 끝나는 마침표에서는 끊어 준다 (2026-09-03 · 시험 화면에서 잡음)
      //   「v = rω. a = rω².」 가 한 덩어리로 묶여 「rω.a」 처럼 붙어 보였다.
      //   ★ 「3.5」 처럼 숫자 사이 점은 안 끊는다 — 뒤에 빈칸이 올 때만 끊는다.
      몸통.split(/(\.\s+)/).forEach(조각 => {
        if (!조각) return;
        if (/^\.\s+$/.test(조각)) 조각들.push({ 글: true, 값: 조각 });
        else if (수식인가(조각)) 조각들.push({ 글: false, 값: 조각 });
        else 조각들.push({ 글: true, 값: 조각 });
      });
      끝난데 = 시작 + 몸통.length;
    }
    if (끝난데 < 글.length) 조각들.push({ 글: true, 값: 글.slice(끝난데) });
    return 조각들;
  }

  function 안전하게(글) {
    return 글.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  return {

    부르기,
    준비됐나() { return 준비됨; },
    라텍스로,

    // 한 줄을 HTML 로 만들어 준다. KaTeX 가 없으면 그냥 글자로 돌려준다.
    그리기(글) {
      if (!준비됨 || !window.katex) return 안전하게(글);
      let 됨 = "";
      나누기(글).forEach(조각 => {
        if (조각.글) { 됨 += 안전하게(조각.값); return; }
        try {
          됨 += window.katex.renderToString(라텍스로(조각.값), {
            throwOnError: true, displayMode: false, output: "html"
          });
        } catch (오류) {
          // ★ 조용히 넘어가지 않는다 — 못 그리면 글자 그대로 보여 준다 (지침서 7절 25번)
          됨 += 안전하게(조각.값);
        }
      });
      return 됨;
    }
  };
})();
