// ============================================================
//  기록소 — 조회수·좋아요를 어디에 쌓을지 담당한다.
// ============================================================
//
//  사용자가 정한 것 (2026-09-02):
//    「학생 좋아요·조회수로 강사가 살아남는 판」
//    그러려면 숫자가 **한군데** 모여야 한다. 각자 폰에만 쌓이면 아무 뜻이 없다.
//
//  ★★★ 두 가지를 갈라 둔다
//    · **모두의 숫자**(조회·좋아요 합계) — 밖의 기록서버에 모인다
//    · **내가 눌렀나**(내좋아요) — 이 브라우저에만 담는다.
//      누가 눌렀는지까지 모으려면 로그인이 필요한데, 지금은 그럴 자리가 아니다.
//      그래서 「한 브라우저에서 한 번」 으로 막는다.
//
//  ★★★ 서버가 없어도 화면은 그대로 돈다.
//    주소를 안 적어 뒀거나 서버가 죽어 있으면 예전처럼 이 브라우저에만 쌓인다.
//    학생 화면이 서버 때문에 멈추면 안 된다 (지침서 7절 25번).
//
//  ★ 깔는 법은 자료/기록서버.gs 맨 위에 적어 뒀다.
// ============================================================

const 기록소 = (() => {

  const 열쇠 = "세진과학.기록.v1";

  // ★★★ 여기에 기록서버 주소를 적으면 그때부터 진짜로 모인다.
  //   비워 두면 예전처럼 이 브라우저에만 쌓인다.
  //   (자료/기록서버.gs 를 구글에 올리고 나오는 웹 앱 URL)
  const 기록서버 = "";

  const 진짜집계 = !!기록서버;

  // 서버에서 받아 온 「모두의 숫자」 를 잠깐 담아 둔다.
  //  ★ 카드가 열 개면 열 번 물어보면 안 된다. 한 번에 몰아서 묻고 여기 담는다.
  const 모두의숫자 = {};          // 아이디 → { 조회, 좋아요 }
  const 바뀌면부를것 = [];

  function 알리기() {
    바뀌면부를것.forEach(ㄷ => { try { ㄷ(); } catch (오류) {} });
  }

  // ---------- 이 브라우저에 담는 것 ----------

  function 통째로읽기() {
    try {
      return JSON.parse(localStorage.getItem(열쇠) || "{}");
    } catch (오류) {
      console.warn("기록이 깨져서 비웠다", 오류);
      return {};
    }
  }

  function 통째로쓰기(값) {
    try { localStorage.setItem(열쇠, JSON.stringify(값)); }
    catch (오류) { console.warn("기록을 못 남겼다", 오류); }
  }

  function 칸(전체, 아이디) {
    if (!전체[아이디]) 전체[아이디] = { 조회: 0, 좋아요: 0, 내좋아요: false, 본날: "" };
    return 전체[아이디];
  }

  function 오늘() {
    const ㄴ = new Date();
    return ㄴ.getFullYear() + "-" + (ㄴ.getMonth() + 1) + "-" + ㄴ.getDate();
  }

  // ---------- 밖의 기록서버 ----------

  //  ★ 보내기만 하고 답은 안 기다린다. 화면이 서버를 기다리게 하면 안 된다.
  //  ★ 구글 Apps Script 는 미리 물어보는 절차(preflight)를 싫어한다.
  //    그래서 text/plain 으로 보낸다 — 그러면 그 절차 없이 바로 간다.
  function 서버에보내기(것) {
    if (!기록서버) return;
    try {
      fetch(기록서버, {
        method: "POST",
        headers: { "Content-Type": "text/plain;charset=utf-8" },
        body: JSON.stringify(것)
      }).catch(() => { /* 못 보내도 화면은 그대로 돈다 */ });
    } catch (오류) { /* 그냥 넘어간다 */ }
  }

  return {

    진짜집계,

    // 화면이 「숫자 바뀌면 알려 줘」 하고 걸어 둔다
    바뀌면알려줘(ㄷ) { if (typeof ㄷ === "function") 바뀌면부를것.push(ㄷ); },

    // ★★★ 여러 영상 숫자를 한꺼번에 물어본다 (격자가 부른다)
    //   하나씩 물어보면 카드 수만큼 오간다. 한 번에 몰아서 묻는다.
    async 여럿물어보기(아이디들) {
      if (!기록서버) return;
      const 물을것 = [...new Set((아이디들 || []).filter(Boolean))].slice(0, 100);
      if (!물을것.length) return;
      try {
        const ㄷ = await fetch(기록서버 + "?v=" + encodeURIComponent(물을것.join(",")));
        if (!ㄷ.ok) return;
        const 답 = await ㄷ.json();
        let 새것 = 0;
        Object.keys(답 || {}).forEach(ㅇ => {
          const ㄱ = 답[ㅇ];
          if (!ㄱ) return;
          모두의숫자[ㅇ] = { 조회: Number(ㄱ.조회) || 0, 좋아요: Number(ㄱ.좋아요) || 0 };
          새것++;
        });
        if (새것) 알리기();
      } catch (오류) { /* 서버가 없거나 느린 것뿐이다 */ }
    },

    // 영상 하나의 숫자를 읽는다
    //  ★ 「모두의 숫자」 는 서버에서, 「내가 눌렀나」 는 이 브라우저에서 온다.
    읽기(아이디) {
      const 내것 = 통째로읽기()[아이디];
      const 내좋아요 = !!(내것 && 내것.내좋아요);

      if (기록서버) {
        const 모두 = 모두의숫자[아이디];
        return 모두
          ? { 조회: 모두.조회, 좋아요: 모두.좋아요, 내좋아요 }
          : { 조회: 0, 좋아요: 0, 내좋아요 };     // 아직 안 받아 왔다
      }
      return 내것
        ? { 조회: 내것.조회, 좋아요: 내것.좋아요, 내좋아요 }
        : { 조회: 0, 좋아요: 0, 내좋아요: false };
    },

    // 재생을 시작했을 때 부른다.
    // 같은 브라우저는 같은 영상을 하루에 한 번만 센다.
    조회올리기(아이디) {
      const 전체 = 통째로읽기();
      const ㅋ = 칸(전체, 아이디);
      if (ㅋ.본날 === 오늘()) return false;   // 오늘 이미 셌다
      ㅋ.조회 += 1;
      ㅋ.본날 = 오늘();
      통째로쓰기(전체);

      if (기록서버) {
        // ★ 화면에는 바로 하나 올려 보여 준다. 서버 답을 기다리지 않는다.
        const 모두 = 모두의숫자[아이디] || (모두의숫자[아이디] = { 조회: 0, 좋아요: 0 });
        모두.조회 += 1;
        서버에보내기({ 할일: "조회", v: 아이디 });
      }
      return true;
    },

    // 좋아요를 눌렀을 때 부른다. 다시 누르면 취소된다.
    // 돌려주는 값 = 누른 뒤 상태
    좋아요누르기(아이디) {
      const 전체 = 통째로읽기();
      const ㅋ = 칸(전체, 아이디);
      const 켤까 = !ㅋ.내좋아요;
      ㅋ.내좋아요 = 켤까;

      if (기록서버) {
        const 모두 = 모두의숫자[아이디] || (모두의숫자[아이디] = { 조회: 0, 좋아요: 0 });
        모두.좋아요 = Math.max(0, 모두.좋아요 + (켤까 ? 1 : -1));
        통째로쓰기(전체);
        서버에보내기({ 할일: "좋아요", v: 아이디, 얼마: 켤까 ? 1 : -1 });
        return { 좋아요: 모두.좋아요, 내좋아요: 켤까 };
      }

      ㅋ.좋아요 = Math.max(0, ㅋ.좋아요 + (켤까 ? 1 : -1));
      통째로쓰기(전체);
      return { 좋아요: ㅋ.좋아요, 내좋아요: 켤까 };
    }

  };
})();
