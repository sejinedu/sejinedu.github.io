// ============================================================
//  기록소 — 조회수·좋아요를 어디에 쌓을지 담당한다.
// ============================================================
//
//  ★★★ 지금은 「네 브라우저 안」 에만 쌓인다. 임시다.
//     - 다른 사람이 들어오면 그 사람 숫자는 0부터 시작한다.
//     - 브라우저 기록을 지우면 같이 날아간다.
//     이건 화면을 눈으로 보려고 넣은 임시 저장이지 진짜 집계가 아니다.
//     (지침서 4절 9번 — 지어낸 값을 굳히지 마라. 그래서 화면에 「임시」 라고 띄운다)
//
//  ★ 진짜로 모으려면 밖에 저장소가 하나 필요하다. 그때 이 파일 안의
//    읽기() · 조회올리기() · 좋아요누르기() 세 개만 바꿔 끼우면 되고,
//    앱.js 와 화면은 하나도 안 고친다. (지침서 6절 21번 — 두 벌 만들지 마라)
//
// ============================================================

const 기록소 = (() => {

  const 열쇠 = "세진과학.기록.v1";
  const 진짜집계 = false;          // 밖의 저장소에 붙으면 true 로 바꾼다

  function 통째로읽기() {
    try {
      return JSON.parse(localStorage.getItem(열쇠) || "{}");
    } catch (오류) {
      // 저장된 게 깨졌으면 조용히 넘어가지 말고 비우고 다시 시작한다
      console.warn("기록이 깨져서 비웠다", 오류);
      return {};
    }
  }

  function 통째로쓰기(값) {
    try {
      localStorage.setItem(열쇠, JSON.stringify(값));
    } catch (오류) {
      console.warn("기록을 못 남겼다", 오류);
    }
  }

  function 칸(전체, 아이디) {
    if (!전체[아이디]) 전체[아이디] = { 조회: 0, 좋아요: 0, 내좋아요: false, 본날: "" };
    return 전체[아이디];
  }

  function 오늘() {
    const ㄴ = new Date();
    return ㄴ.getFullYear() + "-" + (ㄴ.getMonth() + 1) + "-" + ㄴ.getDate();
  }

  return {

    진짜집계,

    // 영상 하나의 숫자를 읽는다
    읽기(아이디) {
      const 전체 = 통째로읽기();
      const ㅋ = 전체[아이디];
      return ㅋ
        ? { 조회: ㅋ.조회, 좋아요: ㅋ.좋아요, 내좋아요: !!ㅋ.내좋아요 }
        : { 조회: 0, 좋아요: 0, 내좋아요: false };
    },

    // 재생을 시작했을 때 부른다.
    // 같은 브라우저는 같은 영상을 하루에 한 번만 센다.
    조회올리기(아이디) {
      const 전체 = 통째로읽기();
      const ㅋ = 칸(전체, 아이디);
      if (ㅋ.본날 === 오늘()) return false;   // 오늘 이미 셌다
      ㅋ.조회 += 1;
      ㅋ.본날 = 오늘();
      통째로쓰기(전체);
      return true;
    },

    // 좋아요를 눌렀을 때 부른다. 다시 누르면 취소된다.
    // 돌려주는 값 = 누른 뒤 상태
    좋아요누르기(아이디) {
      const 전체 = 통째로읽기();
      const ㅋ = 칸(전체, 아이디);
      if (ㅋ.내좋아요) { ㅋ.좋아요 = Math.max(0, ㅋ.좋아요 - 1); ㅋ.내좋아요 = false; }
      else            { ㅋ.좋아요 += 1;                        ㅋ.내좋아요 = true;  }
      통째로쓰기(전체);
      return { 좋아요: ㅋ.좋아요, 내좋아요: ㅋ.내좋아요 };
    }

  };
})();
