// ============================================================
//  과목 → 세부 과목 → 단원 드롭바  (2026-09-22 · 사용자가 정함)
//    「글쓰기에 과목 드롭바를 단원 드롭바 위에 만들어라」
//    「과목과 단원 사이에 세부 과목 드롭바도 만들어라」
//  ★ 글쓰기 창 · 유튜브 가져오기 창이 같이 쓴다.
//  ★ 위를 고르면 아래가 그 안의 것으로 바뀐다. 단원 칸 첫 줄은 「세부 과목 전체」 —
//    단원까지 안 골라도 세부 과목에 바로 붙일 수 있다 (값은 세부 과목 아이디).
// ============================================================
window.과목단원고르개 = function (과목칸, 세부칸, 단원칸, 고를것) {
  const 조상 = 아이디 => (아이디 && 나무.조상들 && 나무.조상들(아이디)) || [];
  const 층 = 아이디 => {        // [과목, 세부 과목] 을 찾는다
    if (!아이디) return ["", ""];
    const ㄱ = 조상(아이디);
    if (!ㄱ.length) return [나무.목록.some(ㅁ => ㅁ.아이디 === 아이디) ? 아이디 : "", ""];
    return [ㄱ[0], ㄱ[1] || 아이디];
  };
  const 채우기 = (칸, 첫말, 가지, 들여쓰기) => {
    칸.replaceChildren(new Option(첫말, ""));
    (function 걷기(가, 깊이) {
      (가 || []).forEach(ㅁ => {
        칸.appendChild(new Option((들여쓰기 ? "   ".repeat(깊이) + (깊이 ? "└ " : "") : "") + ㅁ.이름, ㅁ.아이디));
        if (들여쓰기) 걷기(ㅁ.아래, 깊이 + 1);
      });
    })(가지, 0);
  };
  function 단원채우기(세부아이디, 고를) {
    const ㅊ = 세부아이디 ? 나무.찾기(세부아이디) : null;
    if (!ㅊ) { 단원칸.replaceChildren(new Option("— 세부 과목부터 골라라 —", "")); return; }
    채우기(단원칸, "세부 과목 전체", ㅊ.마디.아래, true);
    단원칸.options[0].value = 세부아이디;
    단원칸.value = 고를 && [...단원칸.options].some(ㅇ => ㅇ.value === 고를) ? 고를 : 세부아이디;
  }
  function 세부채우기(과목아이디, 고를세부, 고를단원) {
    if (!세부칸) return 단원채우기(과목아이디, 고를단원);      // 세부 칸이 없는 옛 창
    const ㅊ = 과목아이디 ? 나무.찾기(과목아이디) : null;
    채우기(세부칸, "— 세부 과목을 골라라 —", ㅊ ? ㅊ.마디.아래 : [], false);
    세부칸.value = 고를세부 && [...세부칸.options].some(ㅇ => ㅇ.value === 고를세부) ? 고를세부 : "";
    단원채우기(세부칸.value, 고를단원);
  }
  채우기(과목칸, "— 과목을 골라라 —", 나무.목록, false);
  const [처음과목, 처음세부] = 층(고를것);
  과목칸.value = 처음과목;
  세부채우기(처음과목, 처음세부, 고를것);
  과목칸.onchange = () => 세부채우기(과목칸.value, "", "");
  if (세부칸) 세부칸.onchange = () => 단원채우기(세부칸.value, "");
};
