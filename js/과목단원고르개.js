//  과목 드롭바 → 단원 드롭바  (2026-09-22 · 사용자가 정함)
//    「글쓰기에 과목 드롭바를 단원 드롭바 위에 만들어라. 과목 드롭바 / 단원 드롭바 이렇게 구성해라」
//  ★ 글쓰기 창 · 유튜브 가져오기 창이 같이 쓴다. 과목을 고르면 단원 칸이 그 과목 것으로 바뀐다.
//  ★ 단원 칸에는 세부 과목(통합과학2 …)부터 끝 단원까지 들여쓰기로 나온다.
// ============================================================
window.과목단원고르개 = function (과목칸, 단원칸, 고를것) {
  const 뿌리찾기 = 아이디 => {
    if (!아이디) return "";
    const 조상 = (나무.조상들 && 나무.조상들(아이디)) || [];
    return 조상.length ? 조상[0] : (나무.목록.some(ㅁ => ㅁ.아이디 === 아이디) ? 아이디 : "");
  };
  function 단원채우기(과목아이디, 고를) {
    단원칸.replaceChildren(new Option("— 단원을 골라라 —", ""));
    const ㅊ = 과목아이디 ? 나무.찾기(과목아이디) : null;
    (function 걷기(가지, 깊이) {
      (가지 || []).forEach(ㅁ => {
        단원칸.appendChild(new Option("   ".repeat(깊이) + (깊이 ? "└ " : "") + ㅁ.이름, ㅁ.아이디));
        걷기(ㅁ.아래, 깊이 + 1);
      });
    })(ㅊ ? ㅊ.마디.아래 : [], 0);
    단원칸.value = 고를 && [...단원칸.options].some(ㅇ => ㅇ.value === 고를) ? 고를 : "";
  }
  과목칸.replaceChildren(new Option("— 과목을 골라라 —", ""));
  나무.목록.forEach(ㅁ => 과목칸.appendChild(new Option(ㅁ.이름, ㅁ.아이디)));
  const 처음과목 = 뿌리찾기(고를것);
  과목칸.value = 처음과목;
  단원채우기(처음과목, 고를것);
  과목칸.onchange = () => 단원채우기(과목칸.value, "");
};
