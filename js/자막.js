// ============================================================
//  자막 — 영상 위에 우리가 직접 그린다
// ============================================================
//
//  사용자가 정한 것 (2026-09-01):
//    「유튜브 자막 워낙 구려가지고」 → 우리가 만든 자막을 얹는다
//
//  자막 글은 자막만들기/자막.py 가 4090 으로 받아적어서
//  자막/<영상아이디>.js 에 담아 둔 것을 쓴다.
//
//  ★ 플레이어는 여기서 안 만든다. js/재생기.js 가 가지고 있고,
//    여기는 거기서 시간만 받아 온다 (지침서 6절 21번 — 두 벌 만들지 마라).

const 자막 = (() => {

  const 담긴것 = {};            // 영상아이디 → 묶음
  const 받는중 = {};

  let 지금줄들 = [];
  let 켜짐 = true;
  let 앞선자리 = -1;
  let 듣개 = null;

  const 자막층 = document.getElementById("자막층");

  // ---------- 자막 크기 ----------
  //  사용자가 정한 것 (2026-09-01): 「자막 크기 좀 크게. 그리고 크기 조절 할 수 있게」
  //  ★ 고른 크기는 브라우저에 담아 둔다. 다음에 열어도 그대로다.

  const 크기열쇠 = "세진과학.자막크기.v1";
  //  ★ 사용자가 정한 것 (2026-09-02):
  //    「글씨는 현재 가장 작은 상태를 기본으로 해주고 그 위아래로 한단계만 더 만들어라」
  //    ⇒ 셋뿐이다. 지금 제일 작던 0.55 가 기본이고, 아래로 하나 위로 하나.
  //    ★ 일곱 단계는 너무 많았다. 폰에서 눌러 가며 맞추기엔 셋이면 넉넉하다.
  //  ★★★ 웹과 폰은 자막 크기 단계가 다르다 (2026-09-03 · 사용자가 정함)
  //    「웹에서는 자막이 너무 작다. 웹에서 자막설정은 지금 크게를 가장 작은 수준으로
  //      해줘 그리고 5단계로 만들어줘」
  //
  //    웹은 화면이 넓어 글씨가 상대적으로 작아 보인다.
  //    ⇒ 폰의 제일 큰 값(0.68)을 웹의 **제일 작은** 값으로 삼고, 거기서 다섯 단계.
  //    ★ 폰은 건드리지 않는다. 세 단계 그대로다.

  const 마우스쓰나 = (() => {
    try { return window.matchMedia("(hover: hover) and (pointer: fine)").matches; }
    catch (오류) { return false; }
  })();

  const 폰크기들 = [
    { 값: 0.45, 이름: "더 작게" },
    { 값: 0.55, 이름: "보통" },
    { 값: 0.68, 이름: "크게" }
  ];
  const 웹크기들 = [
    { 값: 0.68, 이름: "작게" },
    { 값: 0.85, 이름: "조금 작게" },
    { 값: 1.05, 이름: "보통" },
    { 값: 1.30, 이름: "크게" },
    { 값: 1.60, 이름: "아주 크게" }
  ];
  const 크기들 = 마우스쓰나 ? 웹크기들 : 폰크기들;
  let 지금크기 = 마우스쓰나 ? 1.05 : 0.55;

  function 크기입히기() {
    document.documentElement.style.setProperty("--자막배율", 지금크기);
  }

  (function 담긴크기쓰기() {
    try {
      const ㄱ = parseFloat(localStorage.getItem(크기열쇠));
      // ★ 옛 판에서 담아 둔 값(0.8·1.25 …)은 이제 없는 단계다. 목록에 있는 것만 쓴다.
      if (ㄱ && 크기들.some(ㅋ => Math.abs(ㅋ.값 - ㄱ) < 0.001)) 지금크기 = ㄱ;
    } catch (오류) { /* 못 읽으면 보통으로 */ }
    크기입히기();
  })();

  // ---------- 자막 높이 ----------
  //  사용자가 정한 것 (2026-09-02):
  //    「자막이 너무 위에 있어 자막 위치 조절할수 있게 해봐
  //      그리고 디폴트 값은 폰화면 거의 아래에 붙게해」
  //
  //  ★ 자막 밀기(싱크 맞추기)는 없앴다 — 「자막 밀기는 필요 없을듯 없애라」 (2026-09-02).
  //    받아적을 때 소리를 재서 말 시작에 붙이므로 손으로 맞출 일이 없어졌다.

  const 높이열쇠 = "세진과학.자막높이.v1";
  const 높이들 = [
    { 값: 2,  이름: "맨 아래" },
    { 값: 6,  이름: "아래" },
    { 값: 11, 이름: "조금 위" },
    { 값: 17, 이름: "가운데쯤" },
    { 값: 25, 이름: "위" }
  ];
  //  ★ 기본은 맨 아래에서 한 칸 위 (2026-09-02 · 사용자가 정함)
  //    「위치 올리기는 가장 아래에서 한칸 위를 기본값으로 해줘」
  let 지금높이 = 6;

  function 높이입히기() {
    document.documentElement.style.setProperty("--자막바닥", 지금높이 + "%");
  }

  (function 담긴높이쓰기() {
    try {
      const ㄱ = parseFloat(localStorage.getItem(높이열쇠));
      if (!isNaN(ㄱ) && ㄱ >= 0 && ㄱ <= 40) 지금높이 = ㄱ;
    } catch (오류) { /* 못 읽으면 맨 아래로 */ }
    높이입히기();
  })();

  function 불러오기(아이디) {
    if (담긴것[아이디] !== undefined) return Promise.resolve(담긴것[아이디]);
    if (받는중[아이디]) return 받는중[아이디];

    받는중[아이디] = new Promise(풀기 => {
      const ㅅ = document.createElement("script");
      // ★ .json 이 아니라 .js 인 이유 — 파일로 열어도 막히지 않게 (지침서 7절 25번)
      ㅅ.src = "자막/" + 아이디 + ".js?v=" + window.판;
      ㅅ.onload = () => {
        ㅅ.remove();
        const ㄱ = (window.자막모음 || {})[아이디] || null;
        담긴것[아이디] = ㄱ;
        풀기(ㄱ);
      };
      ㅅ.onerror = () => { ㅅ.remove(); 담긴것[아이디] = null; 풀기(null); };
      document.head.appendChild(ㅅ);
    });
    return 받는중[아이디];
  }

  // 줄이 2천 개쯤 된다. 하나씩 훑지 말고 반으로 갈라 찾는다.
  function 찾을자리(초) {
    let 낮 = 0, 높 = 지금줄들.length - 1, 답 = -1;
    while (낮 <= 높) {
      const 가 = (낮 + 높) >> 1;
      if (지금줄들[가].시작 <= 초) { 답 = 가; 낮 = 가 + 1; } else { 높 = 가 - 1; }
    }
    // ★ 여유를 짧게 준다. 길게 주면 말이 끝났는데도 자막이 남아 다음 줄과 겹쳐 보인다.
    if (답 >= 0 && 초 <= 지금줄들[답].끝 + 0.15) return 답;
    return -1;
  }

  // ★★★ 수식은 KaTeX 로 진짜 수식처럼 그린다 (2026-09-02 · 사용자가 정함)
  //   「라텍스가 이쁜데 나중에 적분이나 시그마 이런것도 해야 되」
  //   ★ 자막 파일에 든 글자는 안 건드린다. 그릴 때만 수식으로 바꾼다 (js/수식.js).
  //   ★ KaTeX 를 못 불러와도 자막은 글자 그대로 나온다. 화면이 죽지 않는다.

  function 감싸기(글) {
    if (typeof 수식 !== "undefined") return 수식.그리기(글);
    return 글.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  // ★★★ 말이 끊기는 자리에서 줄을 바꾼다 (2026-09-03 · 사용자가 정함)
  //
  //   「이런것도 있냐면 하고 줄바꿈 해야 한다 그래야 한글 읽기가 더 좋다」
  //
  //   그냥 두면 브라우저가 **자리가 다 찼을 때** 끊는다. 그래서
  //       「이게 어떤 개념하고 좀 비슷할 수 있냐면 A에서 B를
  //        뺀데, A⃗에서 B⃗를 뺀다.」
  //   처럼 「B를」 과 「뺀데」 사이가 갈라진다. 한 덩어리 말이 두 줄로 찢긴다.
  //   ⇒ 「~냐면」 「~니까」 「~는데」 처럼 **말이 한 번 끊기는 자리**를 찾아서 거기서 바꾼다.
  //
  //   ★ 가운데에 가장 가까운 자리를 고른다. 한쪽이 너무 짧으면 보기 흉하다.
  //   ★ 끊을 자리가 없으면 아무것도 안 한다 — 브라우저가 알아서 접게 둔다.
  //   ★ 수식 안은 절대 안 끊긴다. 끊는 자리가 한글 어미 **뒤 빈칸**뿐이라서
  //     기호와 숫자로 된 수식 덩어리 한가운데로는 들어갈 수 없다.

  const 짧으면그냥 = 22;          // 이보다 짧으면 어차피 한 줄이다
  const 한쪽최소 = 0.25;          // 한쪽이 전체의 이만큼은 돼야 한다

  //  말이 한 번 끊기는 자리 — 연결어미와 쉼표·마침표
  const 끊는자리 =
    /(?:냐면|다면|라면|으면|면|니까|는데|은데|ㄴ데|지만|어서|아서|라서|다가|거든|잖아|는지|고요|고|서|며|은|는)[,.]?\s|[,.]\s/g;

  //  한 줄에 몇 글자나 들어가나 — 자막칸 폭과 글자 크기를 재서 본다.
  //  ★★★ 이걸 안 재면 한 줄에 넉넉히 들어갈 자막까지 둘로 쪼갠다 (2026-09-03 에 밟음).
  //    한글은 글자 하나가 글자 크기와 거의 같은 폭을 먹는다. 조금 넉넉하게 잡는다.
  function 한줄글자수() {
    const 폭 = 자막층.clientWidth;
    if (!폭) return 0;                       // 아직 안 그려졌으면 모른다
    const 크기 = parseFloat(getComputedStyle(자막층).fontSize) || 20;
    return Math.floor(폭 / (크기 * 0.98));
  }

  function 두줄로(글) {
    if (!글 || 글.length < 짧으면그냥) return null;
    // ★ 한 줄에 다 들어가면 굳이 안 쪼갠다
    const 들어갈수 = 한줄글자수();
    if (들어갈수 && 글.length <= 들어갈수) return null;
    const 가운데 = 글.length / 2;
    const 최소 = 글.length * 한쪽최소;
    let 고른데 = -1, 가장가까움= Infinity;

    끊는자리.lastIndex = 0;
    let ㅁ;
    while ((ㅁ = 끊는자리.exec(글)) !== null) {
      const 자리 = ㅁ.index + ㅁ[0].length;      // 빈칸까지 삼킨 뒤
      if (자리 < 최소 || 글.length - 자리 < 최소) continue;
      const 떨어짐 = Math.abs(자리 - 가운데);
      if (떨어짐 < 가장가까움) { 가장가까움 = 떨어짐; 고른데 = 자리; }
    }
    if (고른데 < 0) return null;
    return [글.slice(0, 고른데).trim(), 글.slice(고른데).trim()];
  }

  function 자막그리기(글) {
    const 두쪽 = 두줄로(글);
    if (!두쪽) return 감싸기(글);
    return 감싸기(두쪽[0]) + "<br>" + 감싸기(두쪽[1]);
  }

  function 칠하기(자리) {
    if (자리 === 앞선자리) return;
    앞선자리 = 자리;
    if (자리 < 0 || !켜짐) { 자막층.hidden = true; 자막층.textContent = ""; return; }
    // ★ 먼저 보이게 한 다음에 그린다 (2026-09-03)
    //   숨어 있으면 폭이 0 으로 재져서 「한 줄에 들어가나」 를 알 수가 없다.
    자막층.hidden = false;
    자막층.innerHTML = 자막그리기(지금줄들[자리].글);
  }

  function 떼기() {
    if (듣개) { 재생기.시간그만듣기(듣개); 듣개 = null; }
    앞선자리 = -1;
    지금줄들 = [];
    자막층.hidden = true;
    자막층.textContent = "";
  }

  return {

    // 영상을 튼 뒤에 부른다
    async 붙이기(아이디) {
      떼기();
      // ★★★ KaTeX 를 다 받은 다음에 자막을 붙인다 (2026-09-02 에 밟음)
      //   그냥 불러만 두면 첫 몇 줄이 수식이 아니라 글자로 지나가 버린다.
      //   자막 글 받는 것과 같이 기다리므로 늦어지지 않는다.
      const [묶음] = await Promise.all([
        불러오기(아이디),
        (typeof 수식 !== "undefined") ? 수식.부르기() : Promise.resolve()
      ]);
      if (!묶음 || !묶음.줄 || !묶음.줄.length) return null;   // 자막이 없는 영상
      지금줄들 = 묶음.줄;

      듣개 = 초 => 칠하기(찾을자리(초));
      재생기.시간듣기(듣개);
      return 묶음;
    },

    떼기,

    // ★★★ 「자막 없더라」 고 기억해 둔 것을 지운다 (2026-09-02 에 밟음)
    //   자막이 만들어지기 전에 그 영상을 한 번 열면 담긴것[아이디] 에 null 이 박힌다.
    //   그 뒤에 자막이 생겨도 다시 안 물어봐서 영영 안 나온다.
    //   ⇒ 자막 공장이 다 구웠다고 알려 주면 이걸 불러 기억을 지운다.
    잊기(아이디) {
      delete 담긴것[아이디];
      delete 받는중[아이디];
      if (window.자막모음) delete window.자막모음[아이디];
    },

    켜고끄기(값) {
      켜짐 = (값 === undefined) ? !켜짐 : !!값;
      앞선자리 = -2;                 // 다시 칠하게 만든다
      if (!켜짐) { 자막층.hidden = true; 자막층.textContent = ""; }
      return 켜짐;
    },

    켜졌나() { return 켜짐; },
    줄들() { return 지금줄들; },

    크기목록() { return 크기들; },
    지금크기() { return 지금크기; },
    크기바꾸기(값) {
      지금크기 = 값;
      크기입히기();
      try { localStorage.setItem(크기열쇠, String(값)); } catch (오류) { /* 담기만 실패 */ }
    },

    높이목록() { return 높이들; },
    지금높이() { return 지금높이; },
    높이바꾸기(값) {
      지금높이 = Math.max(0, Math.min(40, 값));
      높이입히기();
      try { localStorage.setItem(높이열쇠, String(지금높이)); } catch (오류) {}
      return 지금높이;
    }
  };
})();
