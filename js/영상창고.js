// ============================================================
//  영상 창고 — 화면에서 붙인 영상을 담아 둔다
// ============================================================
//
//  js/동영상.js 는 「손으로 적어 넣는 처음 목록」 이고,
//  여기는 「화면에서 우클릭 → 동영상 링크 연결 로 붙인 것」 을 담는다.
//  둘을 합쳐서 window.동영상목록 을 만든다.
//
//  ★★★ 목록은 이제 파일에 있다 (2026-09-02 · 사용자가 정함)
//    「내가 이 웹사이트 주소만 주면 여기 들어올수 있게 한다」
//
//    전에는 이 브라우저의 서랍(localStorage)에만 쌓였다. 두 가지가 걸렸다 —
//      ① 크롬을 청소하면 붙여 둔 영상이 통째로 날아간다. 백업이 없었다.
//      ② 남한테 주소를 줘도 그 사람 서랍은 비어 있어서 텅 빈 사이트를 본다.
//
//    ⇒ 자료/영상목록.js 가 진짜 목록이고, 브라우저 서랍은 거울이다.
//      바뀔 때마다 서버한테 「파일에 적어 둬라」 하고 보낸다.
//      서버가 없는 자리(파일만 올려 둔 곳)면 그냥 파일을 읽기만 한다.
//
//  ★ 어느 쪽이 새것인지는 시각으로 가린다.
//    서버가 꺼져 있을 때 지운 것이 다시 살아나는 일을 막으려면 이래야 한다.
//
//  ★ 이 파일은 js/동영상.js · 자료/영상목록.js 다음에 불려야 한다.
//    순서는 index.html 이 잡는다.

const 영상창고 = (() => {

  const 열쇠 = "세진과학.붙인영상.v2";
  const 옛열쇠 = "세진과학.붙인영상.v1";

  let 지금시각 = 0;          // 이 목록이 언제 적힌 것인가

  function 서랍읽기() {
    try {
      const ㄱ = JSON.parse(localStorage.getItem(열쇠) || "null");
      if (ㄱ && Array.isArray(ㄱ.목록)) return { 시각: ㄱ.시각 || 0, 목록: ㄱ.목록 };
    } catch (오류) {
      console.warn("붙인 영상이 깨졌다", 오류);
    }
    // ★ 옛 꼴(그냥 배열)도 읽어 준다. 판을 올렸다고 쌓아 둔 게 날아가면 안 된다.
    try {
      const ㄴ = JSON.parse(localStorage.getItem(옛열쇠) || "[]");
      if (Array.isArray(ㄴ) && ㄴ.length) return { 시각: 1, 목록: ㄴ };
    } catch (오류) { /* 옛것도 깨졌으면 그냥 빈 목록 */ }
    return { 시각: 0, 목록: [] };
  }

  function 파일읽기() {
    const ㄱ = window.붙인영상묶음;
    if (ㄱ && Array.isArray(ㄱ.목록)) return { 시각: ㄱ.시각 || 0, 목록: ㄱ.목록 };
    return { 시각: 0, 목록: [] };
  }

  // 둘 중 어느 쪽이 진짜인가
  //  ★★★ 시각만 보면 안 된다 (2026-09-02 에 밟음)
  //    옛 꼴 서랍은 시각을 모른다. 그래서 1 로 친다.
  //    그런데 파일에도 어쩌다 1 이 적혀 있으면 파일이 이겨서
  //    사용자가 여태 붙인 서른한 편 대신 엉뚱한 것이 보인다. 실제로 그럴 뻔했다.
  //  ⇒ 「비어 있는 쪽은 진다」 를 먼저 본다. 빈 목록이 채워진 목록을 이기면 안 된다.
  function 고르기(파일, 서랍) {
    if (!파일.목록.length && 서랍.목록.length) return 서랍;
    if (!서랍.목록.length && 파일.목록.length) return 파일;
    return (서랍.시각 > 파일.시각) ? 서랍 : 파일;
  }

  function 불러오기() {
    const 고른것 = 고르기(파일읽기(), 서랍읽기());
    지금시각 = 고른것.시각;
    return 고른것.목록.slice();
  }

  // 파일에 적어 달라고 서버한테 보낸다.
  //  ★ 서버가 없어도 화면은 그대로 돌아간다. 파일만 올려 둔 자리가 그렇다.
  function 파일에적기(묶음) {
    try {
      fetch("/영상목록", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(묶음)
      }).then(ㄷ => ㄷ.json())
        .then(ㄱ => { if (!ㄱ || !ㄱ.됐나) console.warn("목록을 파일에 못 적었다", ㄱ); })
        .catch(() => { /* 서버가 없는 자리다. 서랍에는 담겼으니 그냥 둔다 */ });
    } catch (오류) { /* fetch 자체가 막힌 자리 */ }
  }

  function 담기(목록) {
    지금시각 = Date.now();
    const 묶음 = { 시각: 지금시각, 목록 };
    let 됐나 = true;
    try { localStorage.setItem(열쇠, JSON.stringify(묶음)); }
    catch (오류) { console.warn("영상을 서랍에 못 담았다", 오류); 됐나 = false; }
    파일에적기(묶음);              // ★ 서랍에 못 담아도 파일에는 적어 본다
    return 됐나;
  }

  // 유튜브 주소에서 11글자 아이디를 뽑는다.
  //  받는 꼴 — youtu.be/ID · watch?v=ID · /embed/ID · /shorts/ID · /live/ID · 아이디만 그대로
  function 아이디뽑기(글) {
    글 = (글 || "").trim();
    if (!글) return null;
    if (/^[A-Za-z0-9_-]{11}$/.test(글)) return 글;            // 아이디만 붙여넣은 경우

    const 자국 = [
      /[?&]v=([A-Za-z0-9_-]{11})/,
      /youtu\.be\/([A-Za-z0-9_-]{11})/,
      /\/embed\/([A-Za-z0-9_-]{11})/,
      /\/shorts\/([A-Za-z0-9_-]{11})/,
      /\/live\/([A-Za-z0-9_-]{11})/
    ];
    for (const ㅈ of 자국) {
      const ㅁ = 글.match(ㅈ);
      if (ㅁ) return ㅁ[1];
    }
    return null;
  }

  // 유튜브한테 제목을 물어본다. 열쇠(API 키) 없이도 되는 길이다.
  //  ★ 못 받아 와도 붙이는 일은 그대로 진행한다. 제목은 나중에 고칠 수 있다.
  async function 제목물어보기(아이디) {
    try {
      const ㄷ = await fetch("https://www.youtube.com/oembed?format=json&url=" +
                             encodeURIComponent("https://www.youtube.com/watch?v=" + 아이디));
      if (!ㄷ.ok) return null;
      const ㄱ = await ㄷ.json();
      return (ㄱ && ㄱ.title) ? ㄱ.title : null;
    } catch (오류) {
      return null;   // 인터넷이 막혔거나 파일로 열어서 막힌 것. 조용히 넘어가되 제목은 비운다
    }
  }

  return {
    아이디뽑기,
    제목물어보기,

    // 파일에 적힌 처음 목록 뒤에 붙인 것을 이어 붙인다.
    //
    // ★ 같은 단원에 같은 영상이 두 군데(파일 · 붙인 것)에서 오면 하나만 남긴다.
    //   2026-09-01 에 실제로 겹쳤다 — 사용자가 화면에서 붙여 둔 영상을
    //   모르고 동영상.js 에도 적어서 같은 강의가 두 개로 보였다.
    //   화면에서 붙인 쪽을 살린다(사용자가 직접 넣은 것이라 제목·강사가 맞다).
    합치기(처음목록) {
      const 담긴것 = 불러오기();
      const 열쇠 = ㅇ => (ㅇ.단원아이디 || "") + "|" + ((ㅇ.아이디 || "").trim());
      const 담긴열쇠 = new Set(담긴것.map(열쇠));
      const 파일것 = (처음목록 || []).filter(ㅇ => !담긴열쇠.has(열쇠(ㅇ)));

      // 파일 안에서도, 담긴 것 안에서도 겹치면 앞엣것만 남긴다
      const 본것 = new Set();
      return [...파일것, ...담긴것].filter(ㅇ => {
        const ㅋ = 열쇠(ㅇ);
        if (본것.has(ㅋ)) return false;
        본것.add(ㅋ);
        return true;
      });
    },

    더하기({ 단원아이디, 강사, 제목, 아이디 }) {
      const 목록 = 불러오기();
      const 새것 = {
        고유: "v" + Date.now().toString(36) + Math.random().toString(36).slice(2, 6),
        단원아이디, 강사, 제목, 아이디
      };
      목록.push(새것);
      if (!담기(목록)) return null;
      return 새것;
    },

    지우기(고유) {
      const 목록 = 불러오기();
      const 남길것 = 목록.filter(ㅇ => ㅇ.고유 !== 고유);
      if (남길것.length === 목록.length) return false;
      return 담기(남길것);
    },

    // 붙여 둔 영상을 고친다 (강사·제목·유튜브 아이디)
    고치기(고유, { 강사, 제목, 아이디 }) {
      const 목록 = 불러오기();
      const ㄱ = 목록.find(ㅇ => ㅇ.고유 === 고유);
      if (!ㄱ) return false;
      if (강사 !== undefined) ㄱ.강사 = 강사;
      if (제목 !== undefined) ㄱ.제목 = 제목;
      if (아이디 !== undefined) ㄱ.아이디 = 아이디;
      return 담기(목록);
    },

    // 다른 단원으로 옮긴다
    //  (사용자가 정한 것 — 「미리보기 동영상 잡고 드래그해서 다른 단원으로」, 2026-09-01)
    옮기기(고유, 새단원아이디) {
      const 목록 = 불러오기();
      const ㄱ = 목록.find(ㅇ => ㅇ.고유 === 고유);
      if (!ㄱ) return false;
      if (ㄱ.단원아이디 === 새단원아이디) return false;
      ㄱ.단원아이디 = 새단원아이디;
      return 담기(목록);
    },

    // 같은 단원에 같은 영상이 이미 붙어 있나
    이미있나(단원아이디, 아이디) {
      return 불러오기().some(ㅇ => ㅇ.단원아이디 === 단원아이디 && ㅇ.아이디 === 아이디);
    },

    // ★★★ 서랍에만 있는 것을 파일로 내려 적는다 (2026-09-02)
    //   사용자가 여태 붙인 영상은 이 브라우저 서랍에만 있었다.
    //   크롬 청소 한 번이면 통째로 날아가는 자리다.
    //   ⇒ 화면이 켜질 때 조용히 한 번 내려 적는다. 사용자는 아무것도 안 눌러도 된다.
    //   ★ 파일이 이미 같거나 더 새것이면 아무것도 안 한다.
    굳히기() {
      const 파일 = 파일읽기();
      const 서랍 = 서랍읽기();
      if (!서랍.목록.length) return false;                  // 서랍이 비었으면 할 일 없다
      if (고르기(파일, 서랍) !== 서랍) return false;          // 파일이 이미 진짜다
      // ★ 옛 꼴 서랍(시각을 모르는 것)은 지금 시각으로 적어 둔다.
      //   그래야 다음부터 어느 쪽이 새것인지 제대로 가려진다.
      const 시각 = (서랍.시각 > 1) ? 서랍.시각 : Date.now();
      파일에적기({ 시각, 목록: 서랍.목록 });
      try { localStorage.setItem(열쇠, JSON.stringify({ 시각, 목록: 서랍.목록 })); }
      catch (오류) { /* 서랍이 꽉 찼어도 파일에는 적었다 */ }
      return true;
    }
  };
})();

// 파일 목록 + 붙인 목록
window.동영상목록 = 영상창고.합치기(window.동영상목록);

// ★ 서랍에만 있던 것을 파일로 내려 적는다 (한 번이면 끝난다)
영상창고.굳히기();
