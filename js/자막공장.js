// ============================================================
//  자막 공장 — 영상을 붙이면 자막이 저절로 만들어지게
// ============================================================
//
//  사용자가 정한 것 (2026-09-02):
//    「동영상 여기 업로드 하면 자동으로 자막 만들어지게 해라.
//      자막 생성되는 동안은 자막 생성중 게이지가 차도록 해라」
//
//  ★ 브라우저는 제 힘으로 컴퓨터 프로그램을 못 돌린다. 막혀 있다.
//    그래서 서버.js 한테 부탁하고, 서버가 자막만들기/자막.py 를 돌린다.
//    ⇒ 서버로 열었을 때만 된다. 파일로 열면(file://) 안 된다.

const 자막공장 = (() => {

  const 상태들 = new Map();      // 영상아이디 → { 상태, 진행, 글 }
  const 시켰다 = new Set();      // 이미 「만들라」 고 한 것 — 두 번 시키지 않는다
  let 물어보는중 = null;
  let 바뀌면 = null;             // 상태가 바뀌면 부를 곳
  let 다되면 = null;             // 한 영상이 다 구워지면 부를 곳

  const 서버쓰나 = location.protocol === "http:" || location.protocol === "https:";

  async function 부탁(길, 아이디) {
    const ㄷ = await fetch(길 + "?v=" + encodeURIComponent(아이디), { cache: "no-store" });
    if (!ㄷ.ok) throw new Error("서버가 " + ㄷ.status);
    return ㄷ.json();
  }

  // 도는 것이 있으면 계속 물어본다. 없으면 조용히 멈춘다.
  function 지켜보기시작() {
    if (물어보는중) return;
    물어보는중 = setInterval(async () => {
      const 볼것 = [...상태들.entries()]
        .filter(([, ㄱ]) => ㄱ.상태 === "도는중" || ㄱ.상태 === "기다림")
        .map(([ㅇ]) => ㅇ);

      if (볼것.length === 0) { clearInterval(물어보는중); 물어보는중 = null; return; }

      try {
        const ㄷ = await fetch("/자막/여럿?v=" + 볼것.join(","), { cache: "no-store" });
        if (!ㄷ.ok) return;
        const 답 = await ㄷ.json();
        let 바뀜 = false;
        const 다된것 = [];
        Object.keys(답).forEach(ㅇ => {
          const 앞 = 상태들.get(ㅇ);
          const 새 = 답[ㅇ];
          if (!앞 || 앞.상태 !== 새.상태 || 앞.진행 !== 새.진행 || 앞.글 !== 새.글) 바뀜 = true;
          // 굽다가 다 된 순간 — 한 번만 잡힌다
          if (앞 && 앞.상태 !== "있음" && (새.상태 === "있음" || 새.상태 === "끝")) 다된것.push(ㅇ);
          상태들.set(ㅇ, 새);
        });
        if (바뀜 && 바뀌면) 바뀌면();
        if (다된것.length && 다되면) 다된것.forEach(ㅇ => 다되면(ㅇ));
      } catch (오류) { /* 서버가 잠깐 안 받는 것뿐이다. 다음에 다시 묻는다 */ }
    }, 1500);
  }

  // 이 서버가 줄을 세울 줄 아나? 한 번만 물어보고 답을 갖고 있는다.
  let 줄세우기답 = null;
  async function 줄세우나() {
    if (줄세우기답 !== null) return 줄세우기답;
    try {
      const ㄷ = await fetch("/자막/판", { cache: "no-store" });
      줄세우기답 = ㄷ.ok ? !!(await ㄷ.json()).줄세우기 : false;
    } catch (오류) { 줄세우기답 = false; }
    return 줄세우기답;
  }

  // 자막을 만들라고 시킨다 (서버가 줄을 세워 하나씩 굽는다)
  async function 만들라고하기(아이디) {
    if (!서버쓰나) {
      return { 상태: "터짐", 진행: 0,
               글: "바탕화면 「세진 과학」 바로가기로 열어야 자막을 만들 수 있다" };
    }
    try {
      const 답 = await 부탁("/자막/만들기", 아이디);
      상태들.set(아이디, 답);
      if (바뀌면) 바뀌면();
      지켜보기시작();
      return 답;
    } catch (오류) {
      // ★ 조용히 넘어가지 않는다. 왜 안 됐는지 남긴다 (지침서 7절 25번)
      const 답 = { 상태: "터짐", 진행: 0, 글: "서버에 연결 못 했다 — 바로가기로 다시 열어 봐라" };
      상태들.set(아이디, 답);
      if (바뀌면) 바뀌면();
      return 답;
    }
  }

  return {

    서버쓰나,

    바뀌면알려줘(ㅎ) { 바뀌면 = ㅎ; },

    // 다 구워진 순간 알려 준다 (화면이 「자막 없더라」 기억을 지우게)
    다되면알려줘(ㅎ) { 다되면 = ㅎ; },

    상태(아이디) { return 상태들.get(아이디) || null; },

    // 자막이 있나 물어본다 (안 만들고 확인만)
    async 물어보기(아이디들) {
      if (!서버쓰나 || !아이디들.length) return;
      try {
        const ㄷ = await fetch("/자막/여럿?v=" + 아이디들.join(","), { cache: "no-store" });
        if (!ㄷ.ok) return;
        const 답 = await ㄷ.json();
        Object.keys(답).forEach(ㅇ => 상태들.set(ㅇ, 답[ㅇ]));
        if (바뀌면) 바뀌면();
        지켜보기시작();

        // ★★★ 자막 없는 것은 시키지 않아도 알아서 줄을 세운다 (2026-09-02)
        //   사용자가 정한 것 — 「이미 있는 것도」. 단추를 누를 일이 없게 한다.
        //   서버가 하나씩만 굽는다. 여기서 한꺼번에 부탁해도 줄로 들어갈 뿐이다.
        //
        //   ★ 줄을 못 세우는 옛 서버면 자동으로 안 시킨다.
        //     화면만 새로 받고 서버는 그대로 돌고 있을 수 있어서다.
        //     그때는 「자막 만들기」 단추가 그대로 남아 하나씩 누를 수 있다.
        if (!(await 줄세우나())) return;

        const 없는것 = Object.keys(답).filter(ㅇ => 답[ㅇ].상태 === "없음" && !시켰다.has(ㅇ));
        for (const ㅇ of 없는것) { 시켰다.add(ㅇ); await 만들라고하기(ㅇ); }
      } catch (오류) { /* 서버 없이 열었을 수도 있다 */ }
    },

    만들기(아이디) { 시켰다.add(아이디); return 만들라고하기(아이디); }
  };
})();
